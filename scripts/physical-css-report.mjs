// Reports physical left/right styling that should usually be logical
// (start/end) in an RTL-first app. Report only - some uses are deliberate
// (e.g. a map overlay pinned to a physical corner) and need a human call.
//   node scripts/physical-css-report.mjs [--out docs/upgrade/physical-css-report.md] [--check]
// --check exits 1 when any NEW file (not in the baseline list below) has a hit.

import { readFile, writeFile } from "node:fs/promises";
import { globSync } from "node:fs";

const PATTERN =
  /(?<![\w-])-?(?:ml|mr|pl|pr|left|right|border-l|border-r|rounded-l|rounded-r|rounded-tl|rounded-tr|rounded-bl|rounded-br|text-left|text-right|float-left|float-right|scroll-ml|scroll-mr)(?:-[\w.[\]/%-]+)?(?![\w-])|(?:margin|padding)-(?:left|right)\s*:|(?<![\w-])(?:left|right)\s*:\s*[-\d]/g;

const args = process.argv.slice(2);
const out = args.includes("--out") ? args[args.indexOf("--out") + 1] : "docs/upgrade/physical-css-report.md";
const files = [
  ...globSync("components/**/*.tsx"),
  ...globSync("app/**/*.{tsx,css}"),
].sort();

const rows = [];
for (const f of files) {
  const lines = (await readFile(f, "utf8")).split("\n");
  lines.forEach((line, i) => {
    // Skip comments and the Tailwind directional arrows in SVG paths.
    if (/^\s*(\/\/|\*|\/\*)/.test(line) || /\sd="/.test(line)) return;
    // A bare "left"/"right" is usually a variable name; only count it as a
    // style when it is written as "left: <number>".
    const hits = [...line.matchAll(PATTERN)].map((m) => m[0]).filter((h) => !/^-?(left|right)$/.test(h));
    if (hits.length) rows.push({ f, n: i + 1, hits: [...new Set(hits)] });
  });
}

const byFile = Object.groupBy(rows, (r) => r.f);
let md = "# Physical left/right CSS report\n\n";
md += `Generated by \`scripts/physical-css-report.mjs\`. ${rows.length} lines in ${Object.keys(byFile).length} files.\n\n`;
md += "Prefer logical utilities: `ms-/me-`, `ps-/pe-`, `start-/end-`, `border-s/e`, `rounded-s/e`, `text-start/end`. Keep a physical one only when the thing is physically placed (a map control, a camera overlay) and add a comment saying so.\n\n";
md += "| File | Line | Found |\n|---|---|---|\n";
for (const r of rows) md += `| \`${r.f}\` | ${r.n} | \`${r.hits.join("`, `")}\` |\n`;
await writeFile(out, md, "utf8");
console.log(`${rows.length} lines in ${Object.keys(byFile).length} files → ${out}`);
